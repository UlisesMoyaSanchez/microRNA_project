"""
protocheck_nimgsa.py -- protocheck on NIMGSA's evaluation, as its released code runs it and as corrected.

Second worked example on a published paper, after analysis/protocheck_mgcnss.py. NIMGSA ships no
split files: its folds are generated by fivefoldcv.py (rows of 20% of the miRNAs zeroed in the
input), so they are rebuilt here with the same RNG order as analysis/nimgsa_rerun.py, which
reproduced the paper's 0.9354. The model AUROC fed to each audit is that fold's measured value
from results/comparison/nimgsa_rerun.json (job 3704), so the margin is per fold, not indicative.

Scenarios, per fold of the published seed (1):
  published_split_only  what fivefoldcv.py actually scores (every positive of the matrix, every
                        zero as a negative), without the encoder input -- a reader's view.
  published             the same plus encoder_edges = the fold's input matrix A0, which is what
                        the model propagates (GraphConv multiplies the similarity graph by A0).
  test_rows             only the held-out rows scored, their zeros as negatives.
  corrected             held-out rows, degree-matched negatives (exact sampler), the AUROC of
                        the model with the similarity's GIP part recomputed.

Training negatives are every zero of A0 (the reconstruction loss treats all of them as 0 targets,
the zeroed held-out rows included).

Not visible to protocheck, by its own scope: the miRNA similarity m-m.txt is fixed and 73.6%
GIP of the full matrix, so held-out associations reach the model through a node feature, not
through an edge. That is the leak worth 6.5 AUROC points in nimgsa_rerun.py.

Usage: python analysis/protocheck_nimgsa.py   (writes results/comparison/protocheck_nimgsa.json)
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from protocheck.audit import audit  # noqa: E402
from training.splits import degree_bins, sample_degree_matched_negatives_exact  # noqa: E402

SEED = 1  # fivefoldcv.py default, the one that gives the paper's 0.9354


def pairs(mask: np.ndarray) -> np.ndarray:
    return np.vstack(np.nonzero(mask)).astype(np.int64)


def main() -> None:
    y = np.loadtxt(ROOT / "data/raw/hmdd_survey/nimgsa/matrix.csv", delimiter=",")
    rerun = json.loads((ROOT / "results/comparison/nimgsa_rerun.json").read_text())
    measured = {r["fold"]: r for r in rerun["runs"] if r["seed"] == SEED}
    n_m, n_d = y.shape
    all_pos_t = torch.from_numpy(pairs(y > 0)).long()

    np.random.seed(SEED)  # same order as fivefoldcv.py / nimgsa_rerun.py
    idx = np.arange(n_m)
    np.random.shuffle(idx)

    out = {"generated_utc": datetime.now(timezone.utc).isoformat(),
           "paper": "NIMGSA (jin2022nimgsa)", "seed": SEED,
           "model_auroc_source": "results/comparison/nimgsa_rerun.json (job 3704)",
           "not_visible_to_protocheck": [
               "m-m.txt similarity fixed across folds, 73.6% GIP of the full matrix "
               "(held-out associations enter as a node feature, not as an edge)"],
           "folds": {}}
    for i in range(5):
        test_rows = np.sort(idx[i * n_m // 5:(i + 1) * n_m // 5])
        a0 = y.copy()
        a0[test_rows, :] = 0
        row_mask = np.zeros_like(y, dtype=bool)
        row_mask[test_rows] = True

        train_pos = pairs(a0 > 0)
        train_neg = pairs(a0 == 0)
        enc = train_pos
        all_pos = pairs(y > 0)
        all_neg = pairs(y == 0)
        test_pos = pairs((y > 0) & row_mask)
        test_neg = pairs((y == 0) & row_mask)

        col_deg = torch.from_numpy(a0.sum(0)).long()
        neg, n_unif, n_nb = sample_degree_matched_negatives_exact(
            torch.from_numpy(test_pos).long(), all_pos_t, degree_bins(col_deg), n_d,
            torch.Generator().manual_seed(1000 * SEED + i))
        m = measured[i + 1]
        common = dict(n_rows=n_m, n_cols=n_d, train_pos=train_pos, train_neg=train_neg)
        scen = {
            "published_split_only": audit(**common, heldout_pos=all_pos, eval_neg=all_neg,
                                          model_auroc=m["model_published"]["full"]),
            "published": audit(**common, heldout_pos=all_pos, eval_neg=all_neg,
                               encoder_edges=enc, model_auroc=m["model_published"]["full"]),
            "test_rows": audit(**common, heldout_pos=test_pos, eval_neg=test_neg,
                               encoder_edges=enc, model_auroc=m["model_published"]["test_rows"]),
            "corrected": audit(**common, heldout_pos=test_pos, eval_neg=neg.numpy(),
                               encoder_edges=enc,
                               model_auroc=m["model_refit"]["test_rows_matched"]),
        }
        out["folds"][str(i + 1)] = {k: v.to_dict() for k, v in scen.items()}
        out["folds"][str(i + 1)]["matched_fallback"] = {"uniform": n_unif, "neighbour": n_nb}
        print(f"\n== fold {i + 1}")
        for name, rep in scen.items():
            print(f"  {name:21s}", "  ".join(f"{f.check}={f.status}" for f in rep.findings))
        if i == 0:
            for name, rep in scen.items():
                print(f"\n---- fold 1, {name} ----")
                print(rep.render())
    path = ROOT / "results/comparison/protocheck_nimgsa.json"
    path.write_text(json.dumps(out, indent=2, default=str))
    print("\nWrote", path)


if __name__ == "__main__":
    main()
